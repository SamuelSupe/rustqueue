interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const initial = localStorage.getItem('rustqueue-language') as Language | null;
  const [language, setLanguageState] = useState<Language>(
    initial === 'zh' || initial === 'en' ? initial : navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en',
  );
  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }, [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage: (next) => {
      localStorage.setItem('rustqueue-language', next);
      document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
      setLanguageState(next);
    },
    t: (key) => messages[language][key] || messages.en[key] || key,
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
